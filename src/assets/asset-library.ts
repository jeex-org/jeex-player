/**
 * `starter:interior-v1` - the local starter object bank.
 *
 * Pure data: the manifest the viewer ships with, extending the CC0 `starter`
 * core set with the demo interior archetypes. A hosted `remote:interior-v1`
 * would replace this file wholesale without any other viewer change.
 *
 * Every archetype, variant and finish is named by its fixed UUID literal
 * (`ARCHETYPE`, `VARIANT` in `catalogue-ids.ts`, `FINISH` in
 * `materials/finish-ids.ts`); its readable name rides along as its
 * display-only `slug`.
 *
 * Invariant: exactly four variants per archetype, the `defaultVariant` is one
 * of them, variant ids are unique library-wide, variant slugs begin with the
 * archetype's family word, and every finish id named here exists in
 * `asset-finishes.ts`. `asset-catalogue.test.ts` enforces all of it.
 *
 * `baseUrl` is the GLB delivery switch and is deliberately ABSENT here. Every
 * archetype names the `model` a catalogue service would serve, but a starter library
 * that ships inside the bundle has nowhere to serve it FROM: with no
 * `baseUrl` the loader resolves no URL, `SceneBuilder.upgradeModels` finds
 * nothing to fetch, and the demo boots with zero requests and the procedural
 * bodies it has always had. A hosted `remote:interior-v1` sets `baseUrl` and the
 * same catalogue starts loading GLBs without another viewer change.
 *
 * `materialSlots` follows the same rule: the library format asks a hosted
 * library to name each material after the slot it dresses, so an entry is needed only
 * where a supplier's GLB disagrees, and this manifest has no GLBs to disagree
 * with yet.
 */

