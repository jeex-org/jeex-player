/**
 * The committed fixture project, judged by the very code that will load it.
 *
 * `tests/fixtures/project/` is the one baked project this repository carries.
 * A fixture that is only READ by a browser test is a fixture nobody checks:
 * these tests run the real boundary — `parseProjectManifest` on the manifest,
 * then `validateScene` on the scene against registries built from the
 * manifest's OWN library — so a typo in either file fails here, in seconds,
 * rather than in Playwright.
 *
 * The independence claim is checked too: not one finish or archetype id of the
 * fixture comes from the catalogues this build bundles, which is what makes
 * the fixture proof that a project draws itself from data. And the JSON
 * agrees with `fixture-ids.ts`, the constants every other test names the
 * fixture's ids by.
 */

import { describe, expect, test } from 'bun:test';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { registriesFromLibrary } from '../scene/registries.js';
import { validateScene } from '../scene/scene-validator.js';
import type { SceneData } from '../scene/types.js';
import { CATALOGUE_REGISTRIES } from './catalogue-registries.js';
import { isProjectDocument, projectLibraryOf } from './project-manifest.js';
import { parseProjectManifest, projectManifestIssues } from './project-manifest.schema.js';
import { INVALID_PROJECT_FIXTURE, PROJECT_FIXTURE as FIXTURE } from '../../tests/fixtures/project/fixture-ids.js';

/** The fixture folder, relative to this module — `src/assets` -> repository root. */
const FIXTURE_DIR = join(import.meta.dirname, '..', '..', 'tests', 'fixtures', 'project');

function read(file: string, dir = FIXTURE_DIR): unknown {
  return JSON.parse(readFileSync(join(dir, file), 'utf8')) as unknown;
}

describe('tests/fixtures/project', () => {
  const document = read('project.json');

  test('is a project document, not a bare scene', () => {
    expect(isProjectDocument(document)).toBe(true);
  });

  const manifest = parseProjectManifest(document);

  test('the manifest passes the boundary schema, under the ids fixture-ids.ts names', () => {
    expect(manifest.formatVersion).toBe(2);
    expect({ projectId: manifest.projectId, bakeId: manifest.bakeId, library: manifest.library.id }).toEqual({
      projectId: FIXTURE.projectId,
      bakeId: FIXTURE.bakeId,
      library: FIXTURE.projectId,
    });
    expect(manifest.library.publisher).toBe(FIXTURE.workspaceId);
    expect(manifest.rights.workspaceId).toBe(FIXTURE.workspaceId);
    expect(manifest.rights.assets).toEqual([
      { assetId: FIXTURE.asset.boxSofa, variantId: FIXTURE.variant.boxSofa, version: '1.0.0', access: 'free' },
    ]);
    expect(manifest.scene).toBe('scene.json');
  });

  test('its one archetype names the GLB the repository carries', () => {
    const object = manifest.library.objects[0]!;
    expect(manifest.library.objects).toHaveLength(1);
    expect(object.id).toBe(FIXTURE.asset.boxSofa);
    // The file keeps its readable name: a name inside the folder carries no identity.
    expect(object.model).toBe('obj/box-sofa@1.0.0.glb');
    expect(object.anchor).toBe('floor');
    expect(object.variants.map((variant) => variant.id)).toEqual([FIXTURE.variant.boxSofa]);
    expect(object.variants[0]!.version).toBe('1.0.0');
    // The GLB is generated by `scripts/make-fixture-glb.ts` and measures
    // exactly this; the format allows 2 % either way, so the check is a tolerance and
    // not an equality — the day the fixture body changes shape the manifest
    // has to follow it, and the day it is re-exported at a hair's difference
    // it does not.
    const measured = [2.1, 0.85, 0.95] as const;
    for (const axis of [0, 1, 2]) expect(Math.abs(object.dims[axis]! / measured[axis]! - 1)).toBeLessThanOrEqual(0.02);
  });

  test('the scene validates against registries built from the manifest library', () => {
    const registries = registriesFromLibrary(projectLibraryOf(manifest), CATALOGUE_REGISTRIES);
    const scene: SceneData = validateScene(read('scene.json'), registries);
    expect(scene.schemaVersion).toBe('2.1');
    expect(scene.id).toBe(FIXTURE.scene);
    expect(scene.assetLibrary).toBe(FIXTURE.projectId);
    expect(scene.nodes.map((node) => node.id)).toEqual(Object.values(FIXTURE.node));
    expect(scene.walls.map((wall) => wall.id)).toEqual(Object.values(FIXTURE.wall));
    expect(scene.walls.flatMap((wall) => (wall.openings ?? []).map((opening) => opening.id))).toEqual([FIXTURE.opening.middle]);
    expect(scene.rooms.map((room) => ({ id: room.id, name: room.name }))).toEqual([
      { id: FIXTURE.room.living, name: 'Living' },
      { id: FIXTURE.room.bedroom, name: 'Bedroom' },
    ]);
    expect(scene.assets).toEqual([
      {
        id: FIXTURE.placement.sofa,
        type: FIXTURE.asset.boxSofa,
        asset: `${FIXTURE.projectId}:${FIXTURE.asset.boxSofa}`,
        variant: FIXTURE.variant.boxSofa,
        room: FIXTURE.room.living,
        position: { x: 2, y: 0, z: 4.2 },
        rotationY: 0,
      },
    ]);
  });

  test('names no id of the catalogues this build bundles', () => {
    const materials = manifest.library.materials.map((material) => material.id);
    expect(materials).toEqual([FIXTURE.material.oak, FIXTURE.material.white]);
    for (const id of materials) expect(CATALOGUE_REGISTRIES.isKnownFinish(id, [])).toBe(false);
    expect(CATALOGUE_REGISTRIES.findCatalogueEntry(FIXTURE.asset.boxSofa)).toBeFalsy();
  });
});

describe('tests/fixtures/project-invalid', () => {
  const document = read('project.json', join(FIXTURE_DIR, '..', 'project-invalid'));

  test('is refused for its scene path alone: everything else is a valid format 2 bake', () => {
    expect(isProjectDocument(document)).toBe(true);
    expect(projectManifestIssues(document).map((issue) => issue.path.join('.'))).toEqual(['scene']);
    expect((document as { projectId: string }).projectId).toBe(INVALID_PROJECT_FIXTURE.projectId);
  });
});
